// Reproducible import; runtime and subsequent builds do not need the Python repo.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';
const root = resolve(import.meta.dirname, '..');
if (!process.argv[2]) throw new Error('Usage: node tool/vendor.mjs /path/to/yt-dlp');
const upstream = resolve(process.argv[2], 'yt_dlp/extractor/youtube/jsc/_builtin/vendor/yt.solver.core.js');
const core = await readFile(upstream, 'utf8');
if (!core.includes('SPDX-License-Identifier: Unlicense') || !core.includes('})(meriyah, astring);')) throw new Error('Unexpected EJS vendor format');
const target = resolve(root, 'src/vendor/yt_solver.js');
await mkdir(dirname(target), { recursive: true });
await writeFile(target, `// Generated by tool/vendor.mjs. Upstream SHA-256: ${createHash('sha256').update(core).digest('hex')}\nimport * as meriyah from 'meriyah';\nimport * as astring from 'astring';\n${core}\nexport default jsc;\n`);
console.log('Imported yt-dlp EJS core into src/vendor/yt_solver.js');
