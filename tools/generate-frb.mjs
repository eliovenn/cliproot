import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const targets = JSON.parse(await readFile(resolve(root, 'tools/native-targets.json'), 'utf8'));
const toolchain = await readFile(resolve(root, 'rust-toolchain.toml'), 'utf8');
const channel = toolchain.match(/^channel\s*=\s*"([^"]+)"/m)?.[1];
if (!channel) throw new Error('The root Rust toolchain must pin a channel.');
await writeFile(resolve(root, 'crates/cliproot-frb/rust-toolchain.toml'),
  '# Generated by tools/generate-frb.mjs; edit the root toolchain and native-targets.json.\n' + toolchain + `targets = ${JSON.stringify(targets)}\n`);
const command = spawnSync('flutter_rust_bridge_codegen', ['generate', '--config-file', 'flutter_rust_bridge.yaml'], {
  cwd: root, stdio: 'inherit', shell: false,
  // Generating host bindings should not install every declared cross target.
  env: { ...process.env, RUSTUP_TOOLCHAIN: channel },
});
if (command.error) throw command.error;
process.exitCode = command.status ?? 1;
