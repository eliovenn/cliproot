"""Use the independent SDK source package, not monorepo-only crate paths."""
import json
import os
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[2]
result = subprocess.run(
    ['node', str(root / 'tools/package-flutter.mjs'), '--json'],
    cwd=root, capture_output=True, text=True, check=True,
)
sdk = Path(json.loads(result.stdout)['path']).resolve()
if not sdk.is_relative_to(root / 'dist'):
    raise RuntimeError('The generated SDK must be inside the workspace dist directory.')
override = root / 'examples/flutter/pubspec_overrides.yaml'
header = '# Generated by tools/ci/prepare_sdk.py.\n'
if override.exists() and not override.read_text().startswith(header):
    raise RuntimeError('Refusing to overwrite a user-owned pubspec override.')
override.write_text(header + 'dependency_overrides:\n  cliproot_flutter:\n    path: '
                    + json.dumps(str(sdk)) + '\n', encoding='utf8')
if os.environ.get('GITHUB_OUTPUT'):
    with open(os.environ['GITHUB_OUTPUT'], 'a', encoding='utf8') as output:
        output.write(f'sdk-path={sdk}\n')
print(f'Validation uses the independent SDK: {sdk}')
