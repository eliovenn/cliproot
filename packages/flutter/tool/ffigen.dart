import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    input: Input(entryPoints: [root.resolve('src/native_library.h')]),
    visitors: [
      Visitor(
        func: (function) {
          function.isIncluded =
              function.originalName == 'cliproot_native_library_path';
          if (function.isIncluded) function.name = 'cliprootNativeLibraryPath';
          function.recordUse = function.isIncluded;
        },
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/src/native/native_library.g.dart'),
      ),
      style: const NativeExternalBindings(
        assetId: 'package:cliproot_flutter/src/native/native_library.g.dart',
      ),
      // FFIgen's recorded-use configuration is experimental, but is kept in
      // the generator rather than hand-editing generated symbol maps.
      // ignore: experimental_member_use
      recordUseMapping: root.resolve(
        'lib/src/third_party/native_library.record_use_mapping.g.dart',
      ),
      preamble: '''
// Copyright (c) 2026 Cliproot contributors. SPDX-License-Identifier: MIT
// Generated by package:ffigen from src/native_library.h. Do not edit manually.
''',
    ),
  ).generate();
}
